function interpolate(template, values = {}) {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => (
    values[key] === undefined || values[key] === null ? match : String(values[key])
  ));
}

export function normalizeLanguagePreference(value) {
  return SUPPORTED_LANGUAGES.has(value) ? value : "auto";
}

export function resolveLanguage(preference, browserLanguage = globalThis.navigator?.language ?? "en") {
  const normalized = normalizeLanguagePreference(preference);
  if (normalized !== "auto") return normalized;
  return String(browserLanguage).toLocaleLowerCase().startsWith("ru") ? "ru" : "en";
}

export function translatorFor(language) {
  const resolved = resolveLanguage(language);
  return (key, values = {}) => interpolate(STRINGS[resolved][key] ?? STRINGS.en[key] ?? key, values);
}

export function applyDocumentLanguage(root, language, translate = translatorFor(language)) {
  const documentElement = root.documentElement ?? root;
  documentElement.lang = language;
  root.querySelectorAll?.("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });
  root.querySelectorAll?.("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll?.("[data-i18n-title]").forEach((element) => {
    element.title = translate(element.dataset.i18nTitle);
  });
  root.querySelectorAll?.("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
  });
}

export async function initializeLanguageSelect(select, {
  root = document,
  initialPreference,
  onChange,
} = {}) {
  const saved = await chrome.storage.local.get(STORAGE_KEY);
  let preference = normalizeLanguagePreference(initialPreference ?? saved[STORAGE_KEY]);
  let language = resolveLanguage(preference, chrome.i18n?.getUILanguage?.() || globalThis.navigator?.language);
  let translate = translatorFor(language);

  const controller = {
    get preference() { return preference; },
    get language() { return language; },
    t(key, values) { return translate(key, values); },
    refresh() {
      language = resolveLanguage(preference, chrome.i18n?.getUILanguage?.() || globalThis.navigator?.language);
      translate = translatorFor(language);
      if (select) select.value = preference;
      applyDocumentLanguage(root, language, translate);
      return language;
    },
  };

  controller.refresh();
  select?.addEventListener("change", async () => {
    preference = normalizeLanguagePreference(select.value);
    controller.refresh();
    await chrome.storage.local.set({ [STORAGE_KEY]: preference });
    await onChange?.(controller);
  });

  chrome.storage.onChanged.addListener((changes, areaName) => {
    if (areaName !== "local" || !changes[STORAGE_KEY]) return;
    preference = normalizeLanguagePreference(changes[STORAGE_KEY].newValue);
    controller.refresh();
    onChange?.(controller);
  });

  return controller;
}
